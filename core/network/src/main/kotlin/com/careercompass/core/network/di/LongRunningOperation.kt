package com.careercompass.core.network.di

/**
 * **오래 걸리는 서버 작업** — 서버가 우리 통제 밖의 자원(사용자가 올린 파일, 사용자가 준 외부 사이트)을
 * 가져와 처리하는 동안 클라이언트가 응답을 기다리는 호출이다.
 *
 * 일반 API 타임아웃(read 10초·call 30초)은 우리 서버가 자기 DB 를 읽어 돌려주는 시간을 기준으로 잡은 값이라
 * 여기에는 맞지 않는다. 그 값을 그대로 쓰면 서버가 아직 일하는 중인데 클라이언트가 먼저 포기하고, 사용자는
 * 기능이 지원되지 않는다고 오해한 채 재시도해 같은 작업을 처음부터 다시 시킨다.
 *
 * **목록으로 두는 이유는 예외를 클라이언트마다 흩어 놓지 않기 위해서다.** 업로드 하나만
 * `NetworkModule.provideUploadOkHttpClient` 에 박아 두었더니, 같은 성격인 게시판 구조 감지가 일반 타임아웃으로
 * 새어 나갔다(#134). 새 엔드포인트가 이 성격이면 항목을 여기에 더하고 전용 Retrofit 을 만들어
 * `ServiceModule` 에서 물린다 — 판정 기준과 값이 한자리에 남는다.
 *
 * **어느 값도 무제한이 아니다.** 상한이 없으면 실패한 호출이 끝나지 않아 사용자가 진행 표시만 보며 화면에
 * 갇힌다. 서버 구현이 없어 실제 소요는 재지 못했고, 값은 「무엇을 기다리는가」와 「사용자가 그 앞에서
 * 기다리는가」로 정했다.
 */
public enum class LongRunningOperation(
    /** 한 구간(바이트 사이 간격)의 상한. 서버가 살아 있으나 느린 것과 죽은 것을 가른다. */
    internal val ioTimeoutSeconds: Long,
    /** 재시도·리다이렉트를 포함한 호출 전체의 상한. */
    internal val callTimeoutSeconds: Long,
) {
    /**
     * `POST /past-applications/upload` — 파일 본문 전송 + 텍스트 추출 + LLM 분류(기능 스펙 F1-4).
     *
     * 소요가 본문 크기와 문서 길이에 함께 비례해 가장 길다. 온보딩 업로드는 사용자가 여러 건을 올려 두고
     * 기다리는 자리라 5분까지 허용한다.
     */
    Upload(ioTimeoutSeconds = 60L, callTimeoutSeconds = 5 * 60L),

    /**
     * `POST /boards/detect` — 외부 사이트 HTML 수신 + 목록 패턴 분석 + 최근 게시글 5건 파싱(기능 스펙 F2-1).
     *
     * 대상이 우리가 통제하지 않는 학교·채용 사이트라 느린 곳은 서버가 HTML 을 받는 데만 수십 초가 걸린다.
     * 그래서 한 구간(read)에는 업로드와 같은 1분을 준다.
     *
     * 호출 전체는 2분으로 업로드보다 짧게 끊는다 — 감지는 등록 흐름 한가운데라 사용자가 스피너를 **보면서**
     * 기다린다. 여기서 5분을 기다리게 하면 사용자가 앱이 멈췄다고 판단해 앱을 내리는 쪽이 먼저다. 2분은
     * 「느린 사이트는 통과시키되, 응답 없는 사이트는 사용자를 붙잡아 두기 전에 끊는다」는 절충이다.
     */
    BoardDetect(ioTimeoutSeconds = 60L, callTimeoutSeconds = 2 * 60L),

    /**
     * `GET /applications/{id}/stream` — 지원서 초안 생성의 SSE 진행 스트림(기능 스펙 F4-1).
     *
     * 앞의 둘과 성격이 하나 다르다. 업로드·감지는 **한 번의 응답**을 오래 기다리는 것이고, 이쪽은 응답이
     * 이미 열린 채로 **여러 번 나눠 온다**. 그래서 두 값의 뜻이 갈린다.
     *
     * `ioTimeoutSeconds` 는 **항목 하나가 LLM 을 도는 시간**의 상한이다. 항목 사이에는 바이트가 흐르지
     * 않으므로 이 값이 곧 「다음 항목을 얼마나 기다려 주는가」다. 업로드와 같은 1분으로는 짧다 — 자소서
     * 항목 하나는 문항이 길면 그보다 더 걸린다. 2분을 준다. 서버가 하트비트 주석(`:`)을 보내면 그 간격마다
     * 초기화되므로 실제로는 더 관대해진다.
     *
     * `callTimeoutSeconds` 는 **스트림 전체**의 상한이고, 업로드와 같은 5분이다. 문항 수(보통 3~5개)에
     * 항목별 최악을 곱하면 그보다 길지만, 그 곱을 그대로 상한으로 삼지 않는다 — 사용자가 진행 표시 앞에서
     * 기다릴 수 있는 시간이 먼저 끝나고, 그 뒤로는 앱이 멈춘 것과 구분되지 않는다. 5분에 끊어도 **받은 항목은
     * 남고**, 이어 받는 길은 재연결이 아니라 `POST /applications` 로 지금 상태를 다시 받는 것이다
     * (`docs/spec/canon.md` 「지원서 규칙」). 즉 상한을 짧게 두는 값이 잃는 것보다 크다.
     */
    ApplicationStream(ioTimeoutSeconds = 2 * 60L, callTimeoutSeconds = 5 * 60L),
}
